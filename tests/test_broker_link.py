def _outcome(validate, url):
    try:
        value = validate(url)
    except (tunnel.TunnelError, stdio_adapter.StdioAdapterError) as error:
        return (type(error).__name__, str(error))
    except ValueError as error:
        # urllib's own messages vary across Python versions; record only that
        # the error came from urllib rather than from the validator itself.
        message = str(error)
        return (type(error).__name__, message if message in FIXED_MESSAGES else "urllib")
    except Exception as error:  # non-string inputs: record only the type
        return (type(error).__name__, None)
    return ("ok", value)


def _client_environment(url: str) -> object:
    data = f"CARDPUTER_CLIENT_KEY={KEY}\nCARDPUTER_BROKER_URL={url}\n".encode()
    return client_environment._parse(data).url


def _stdio(url: object) -> str:
    return stdio_adapter.HTTPBrokerAdapter(url, KEY)._url  # type: ignore[arg-type]


def outcomes(url: object) -> tuple[tuple[str, object], ...]:
    results = [
        _outcome(client.validate_url, url),
        _outcome(tunnel._local_broker_url, url),
        _outcome(operator_client.operator_base_url, url),
        _outcome(_client_environment, url) if isinstance(url, str) else ("n/a", None),
        _outcome(_stdio, url),
    ]
    return tuple(results)


